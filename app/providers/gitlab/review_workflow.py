def _summary_markdown(mr: dict, review: dict) -> str:
    metrics = review.get("metrics", {})
    lines = [
        "## AI Code Review", "",
        f"**Merge request:** {mr.get('title') or 'Untitled'}",
        f"**Risk level:** `{review.get('risk_level', 'unknown').upper()}`",
        f"**Accepted findings:** {metrics.get('accepted_findings', 0)}", "",
        review.get("overview", "Review completed."), "",
    ]
    findings = review.get("findings", [])
    if not findings:
        lines.append("No actionable findings were identified by the configured review agents.")
    else:
        lines.extend(["### Findings", ""])
        for finding in findings:
            lines.append(
                f"- **{finding['severity'].upper()} – {finding['title']}** "
                f"(`{finding['file_path']}:{finding['line_number']}`): "
                f"{finding['description']}"
            )
    lines.extend(["", "_Generated by the AI Code Review Agent. Please validate findings before merging._"])
    return "\n".join(lines)


async def run_gitlab_review(
    client: GitLabClient,
    project_id: str,
    merge_request_iid: int,
    ai_client,
    *,
    min_confidence: float = 0.65,
    workspace_group_id: str | None = None,
    publish_comments: bool = True,
) -> dict:
    mr = await client.get_merge_request(project_id, merge_request_iid)
    if not mr.get("diff_text", "").strip():
        raise ValueError("Merge request contains no reviewable text diff")

    # First automated version reviews the diff itself. Repository checkout/context retrieval
    # will be moved into an isolated worker in the background-processing milestone.
    # Retrieve indexed project context and project-specific review rules.
    os = __import__("os")
    configured_ids = [x.strip() for x in os.getenv("KNOWLEDGE_PROJECT_IDS", "").split(",") if x.strip()]
    group_id = workspace_group_id or os.getenv("KNOWLEDGE_GROUP_ID", "").strip() or None
    workspace_ids = indexed_workspace_project_ids(group_id)
    project_ids = list(dict.fromkeys([str(project_id), *workspace_ids, *configured_ids]))
    parsed_query = f"{mr.get('title') or ''}\n{mr.get('description') or ''}\n{mr['diff_text']}"
    retrieved = hybrid_retrieve(project_ids, parsed_query, limit=10, max_chars=30000)
    symbols = search_symbols(project_ids, parsed_query, limit=25)
    graph = dependency_graph(str(project_id))
    rules = load_rules(str(project_id))

    # Enrich the MR review with Java method-flow and cross-repository evidence
    # already present in the shared knowledge database.
    parsed = parse_git_diff(mr["diff_text"])
    changed_paths = [item.new_path or item.old_path for item in parsed.files if item.new_path or item.old_path]
    requested_ref = mr.get("target_branch") or None
    available_refs = indexed_refs(str(project_id))
    if requested_ref in available_refs:
        selected_ref = requested_ref
        ref_fallback = False
    elif available_refs:
        preferred = "main" if "main" in available_refs else ("master" if "master" in available_refs else available_refs[0])
        selected_ref = preferred
        ref_fallback = bool(requested_ref and selected_ref != requested_ref)
    else:
        selected_ref = requested_ref
        ref_fallback = bool(requested_ref)
    java_flows = analyze_java_flows(str(project_id), selected_ref)
    flow_impact = analyze_flow_impact(str(project_id), changed_paths, selected_ref)
    cross_candidate_ids = list(dict.fromkeys([str(project_id), *workspace_ids, *configured_ids]))
    cross_impact = cross_project_impact(
        str(project_id), changed_paths, selected_ref,
        cross_candidate_ids if cross_candidate_ids else None,
    )
    rule_context = "\n\nPROJECT REVIEW RULES\n" + __import__("json").dumps(rules, ensure_ascii=False) if rules else ""
    symbol_context = "\n\nREPOSITORY SYMBOLS (verify against source):\n" + "\n".join(
        f"{item['kind']} {item['name']} at {item['path']}:{item['start_line']}" for item in symbols
    ) if symbols else ""
    graph_context = "\n\nIMPORT RELATIONSHIPS (heuristic; unresolved imports are not errors):\n" + "\n".join(
        f"{edge['source']} imports {edge['import']}" for edge in graph.get("edges", [])[:80]
    ) if graph.get("edges") else ""
    import json
    flow_context = "\\n\\nJAVA METHOD-FLOW ANALYSIS (static heuristic; validate evidence):\\n" + json.dumps({
        "method_flows": java_flows.get("method_flows", [])[:160],
        "dto_usage": java_flows.get("dto_usage", [])[:80],
        "changed_flow_impact": flow_impact,
    }, ensure_ascii=False) if java_flows.get("java_files") else ""
    cross_context = "\\n\\nCROSS-PROJECT IMPACT (indexed repositories only; confidence is evidence-based):\\n" + json.dumps(cross_impact, ensure_ascii=False) if cross_impact.get("consumer_findings") else ""
    context = (retrieved.get("context") or "") + symbol_context + graph_context + rule_context + flow_context + cross_context
    context = context[:180000]
    review = await run_multi_agent_review(
        ai_client, mr["diff_text"], context=context or None, min_confidence=min_confidence
    )
    review["repository_context"] = {"chunks_used": retrieved.get("chunks", 0), "sources": retrieved.get("sources", []), "rules_loaded": bool(rules), "symbols_used": len(symbols), "dependency_edges_available": len(graph.get("edges", [])), "retrieval": retrieved.get("retrieval"), "java_files_analyzed": java_flows.get("java_files", 0), "method_flows_available": len(java_flows.get("method_flows", [])), "potential_callers": len(flow_impact.get("potential_callers", [])), "cross_project_findings": len(cross_impact.get("consumer_findings", [])), "changed_paths": changed_paths, "indexed_refs": available_refs, "analysis_ref": selected_ref, "target_ref_fallback_used": ref_fallback, "workspace_projects_considered": len(project_ids)}
    posted_discussions = 0
    skipped_inline = 0
    errors: list[str] = []
    summary_published = False

    if publish_comments:
        refs = mr.get("diff_refs") or {}
        base_sha = refs.get("base_sha")
        start_sha = refs.get("start_sha") or base_sha
        head_sha = refs.get("head_sha")

        for finding in review.get("findings", []):
            path = finding["file_path"]
            if not (base_sha and start_sha and head_sha):
                skipped_inline += 1
                continue
            position = {
                "position_type": "text",
                "base_sha": base_sha,
                "start_sha": start_sha,
                "head_sha": head_sha,
                "old_path": path,
                "new_path": path,
                "new_line": finding["line_number"],
            }
            body = (
                f"**{finding['severity'].upper()} · {finding['category']} · "
                f"Confidence {finding['confidence']:.0%}**\\n\\n"
                f"{finding['title']}\\n\\n{finding['description']}\\n\\n"
                f"**Recommendation:** {finding['recommendation']}\\n\\n"
                f"**Evidence:** `{finding['evidence']}`"
            )
            try:
                await client.create_merge_request_discussion(
                    project_id, merge_request_iid, body, position
                )
                posted_discussions += 1
            except Exception:
                errors.append(
                    f"Could not publish inline comment for {path}:{finding['line_number']}"
                )

        await client.create_merge_request_note(
            project_id, merge_request_iid, _summary_markdown(mr, review)
        )
        summary_published = True

    return {
        "status": "completed" if publish_comments else "preview",
        "project_id": str(project_id),
        "merge_request_iid": merge_request_iid,
        "merge_request_url": mr.get("web_url"),
        "review": review,
        "published": publish_comments,
        "published_inline_comments": posted_discussions,
        "skipped_inline_comments": skipped_inline,
        "publication_warnings": errors,
        "summary_published": summary_published,
        "message": (
            "Review comments were published to GitLab."
            if publish_comments
            else "Preview only. No comments were written to GitLab."
        ),
    }
